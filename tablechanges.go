package main

import (
	"context"
	"database/sql"
	"fmt"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
)

// RowIdentity identifies one physical row version, including partitioned tables
// and tables without a primary key. xmin prevents overwriting concurrent edits.
type RowIdentity struct {
	TableOID string `json:"tableOID"`
	CTID     string `json:"ctid"`
	Version  string `json:"version"`
}

type TableChange struct {
	Kind     string             `json:"kind"`
	Identity *RowIdentity       `json:"identity"`
	Values   map[string]*string `json:"values"`
}

type tableQuerier interface {
	QueryContext(context.Context, string, ...any) (*sql.Rows, error)
}

func readTableColumns(ctx context.Context, db tableQuerier, schema, table string) ([]ColumnInfo, error) {
	rows, err := db.QueryContext(ctx, `
		SELECT column_name, data_type, is_nullable = 'YES',
		       column_default IS NOT NULL OR is_identity = 'YES',
		       is_generated = 'ALWAYS' OR (is_identity = 'YES' AND identity_generation = 'ALWAYS'),
		       is_identity = 'YES' OR COALESCE(column_default LIKE 'nextval(%', false),
		       COALESCE(column_default, ''), COALESCE(generation_expression, ''), COALESCE(identity_generation, '')
		FROM information_schema.columns
		WHERE table_schema = $1 AND table_name = $2 ORDER BY ordinal_position`, schema, table)
	if err != nil {
		return nil, fmt.Errorf("Could not read table columns: %w", err)
	}
	defer rows.Close()
	columns := make([]ColumnInfo, 0)
	for rows.Next() {
		var column ColumnInfo
		if err := rows.Scan(&column.Name, &column.DataType, &column.Nullable, &column.HasDefault, &column.Generated, &column.AutoIncrement, &column.DefaultValue, &column.GenerationExpression, &column.IdentityGeneration); err != nil {
			return nil, fmt.Errorf("Could not read table columns: %w", err)
		}
		columns = append(columns, column)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("Could not read table columns: %w", err)
	}
	return columns, nil
}

// SaveTableChanges applies the entire draft in one transaction. Any constraint
// failure or changed/deleted row rolls back every edit, insertion and deletion.
func (s *PostgresService) SaveTableChanges(connectionID, schema, tableName string, changes []TableChange) error {
	if len(changes) == 0 {
		return nil
	}
	if len(changes) > 1000 {
		return fmt.Errorf("Save at most 1,000 row changes at a time")
	}
	db, err := s.connection(connectionID)
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("Could not begin saving: %w", err)
	}
	defer tx.Rollback()
	columns, err := readTableColumns(ctx, tx, schema, tableName)
	if err != nil {
		return err
	}
	if len(columns) == 0 {
		return fmt.Errorf("That table is no longer available or has no accessible columns")
	}
	knownColumns := make(map[string]ColumnInfo, len(columns))
	for _, column := range columns {
		knownColumns[column.Name] = column
	}
	quotedTable := pgx.Identifier{schema, tableName}.Sanitize()
	for index, change := range changes {
		for name := range change.Values {
			column, ok := knownColumns[name]
			if !ok {
				return fmt.Errorf("Column %q is no longer available", name)
			}
			if column.Generated {
				return fmt.Errorf("Column %q is generated by PostgreSQL and cannot be edited", name)
			}
		}
		names, placeholders, assignments := []string{}, []string{}, []string{}
		args := []any{}
		// Use catalog order so SQL and parameter ordering are deterministic.
		for _, column := range columns {
			value, ok := change.Values[column.Name]
			if !ok {
				continue
			}
			var parameter any
			if value != nil {
				parameter = *value
			}
			args = append(args, parameter)
			name := pgx.Identifier{column.Name}.Sanitize()
			placeholder := fmt.Sprintf("$%d", len(args))
			names = append(names, name)
			placeholders = append(placeholders, placeholder)
			assignments = append(assignments, name+" = "+placeholder)
		}
		var query string
		switch change.Kind {
		case "insert":
			query = "INSERT INTO " + quotedTable + " DEFAULT VALUES"
			if len(names) > 0 {
				query = "INSERT INTO " + quotedTable + " (" + strings.Join(names, ", ") + ") VALUES (" + strings.Join(placeholders, ", ") + ")"
			}
		case "update", "delete":
			if change.Identity == nil || change.Identity.TableOID == "" || change.Identity.CTID == "" || change.Identity.Version == "" {
				return fmt.Errorf("Row change %d has no row identity; refresh the table", index+1)
			}
			if change.Kind == "delete" && len(change.Values) != 0 {
				return fmt.Errorf("A deleted row cannot also contain edits")
			}
			if change.Kind == "update" && len(assignments) == 0 {
				return fmt.Errorf("Row change %d has no edited values", index+1)
			}
			start := len(args) + 1
			args = append(args, change.Identity.TableOID, change.Identity.CTID, change.Identity.Version)
			where := fmt.Sprintf(" WHERE tableoid = $%d::oid AND ctid = $%d::tid AND xmin = $%d::xid", start, start+1, start+2)
			query = "DELETE FROM " + quotedTable + where
			if change.Kind == "update" {
				query = "UPDATE " + quotedTable + " SET " + strings.Join(assignments, ", ") + where
			}
		default:
			return fmt.Errorf("Unknown row change %q", change.Kind)
		}
		result, err := tx.ExecContext(ctx, query, args...)
		if err != nil {
			return fmt.Errorf("Could not save row change %d; no changes were saved: %w", index+1, err)
		}
		affected, err := result.RowsAffected()
		if err != nil {
			return fmt.Errorf("Could not verify row change %d: %w", index+1, err)
		}
		if affected != 1 {
			return fmt.Errorf("Row change %d could not be applied. The row may have changed or been deleted by another session. No changes were saved; discard and refresh before retrying", index+1)
		}
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("Could not commit changes: %w", err)
	}
	return nil
}
